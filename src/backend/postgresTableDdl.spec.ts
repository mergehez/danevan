// PostgreSQL's whole modify-table plan is generated text, so these drive the real builder and
// assert the exact statements — including the two changes the dialect refuses.
import { describe, expect, it } from 'vitest';
import type { TableColumnInfo, TableForeignKeyInfo, TableIndexInfo, TableInfo } from '../shared/types';
import { buildPostgresModifyTableStatements, indexSignature, type PostgresTableDdlDeps } from './postgresTableDdl.ts';
import type { ModifySchemaColumn, ModifySchemaPlan } from './useSqliteDriver.ts';

const deps: PostgresTableDdlDeps = {
    escapeSqlString: (value) => `'${value.replaceAll("'", "''")}'`,
    normalizeOptionalText: (value) => (value?.trim() ? value.trim() : null),
    quoteIdentifier: (identifier) => `"${identifier}"`,
};

function column(overrides: Partial<ModifySchemaColumn> = {}): ModifySchemaColumn {
    return {
        name: 'name',
        type: 'text',
        notNull: false,
        defaultValue: null,
        isPrimaryKey: false,
        primaryKeyOrdinal: null,
        isAutoIncrement: false,
        comment: null,
        collation: null,
        onUpdate: null,
        ...overrides,
    };
}

/** A column the plan re-sends under the same name. */
function keptColumn(overrides: Partial<ModifySchemaColumn> = {}): ModifySchemaColumn {
    const kept = column(overrides);

    return { ...kept, originalName: overrides.originalName ?? kept.name };
}

function columnInfo(overrides: Partial<TableColumnInfo> = {}): TableColumnInfo {
    return {
        cid: 0,
        name: 'name',
        type: 'text',
        notNull: false,
        defaultValue: null,
        isPrimaryKey: false,
        primaryKeyOrdinal: null,
        isAutoIncrement: false,
        comment: null,
        collation: null,
        onUpdate: null,
        ...overrides,
    };
}

function indexInfo(overrides: Partial<TableIndexInfo> = {}): TableIndexInfo {
    return { name: 'ix_name', columns: [], isUnique: false, origin: '', isPartial: false, ...overrides };
}

function foreignKeyInfo(overrides: Partial<TableForeignKeyInfo> = {}): TableForeignKeyInfo {
    return { id: 1, name: 'fk_owner', sequence: 0, table: 'users', from: 'owner_id', to: 'id', onUpdate: 'NO ACTION', onDelete: 'NO ACTION', match: 'NONE', ...overrides };
}

function tableInfo(overrides: Partial<TableInfo> = {}): TableInfo {
    return { name: 'orders', columns: [], indexes: [], foreignKeys: [], rowCount: 0, ...overrides };
}

function plan(overrides: Partial<ModifySchemaPlan> = {}): ModifySchemaPlan {
    return {
        table: { name: 'orders', comment: null, engine: null, collation: null, options: null },
        columns: [],
        keys: [],
        foreignKeys: [],
        indexes: [],
        ...overrides,
    };
}

describe('indexSignature', () => {
    it('ignores the comment, which PostgreSQL cannot compare', () => {
        const base = { name: 'ix_created', comment: null, isUnique: false, type: 'BTREE', columns: [{ columnName: 'Created', order: 'DESC' }] };

        expect(indexSignature({ ...base, comment: 'fresh' })).toBe(indexSignature(base));
        expect(indexSignature({ ...base, isUnique: true })).not.toBe(indexSignature(base));
        expect(indexSignature({ ...base, type: null })).toBe('created:DESC::0::');
    });
});

describe('buildPostgresModifyTableStatements', () => {
    it('adds a column with its collation, identity and comment', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo(),
            plan({ columns: [column({ name: 'id', type: 'integer', notNull: true, isAutoIncrement: true, collation: 'C', comment: 'pk' })] })
        );

        expect(statements).toEqual([
            'ALTER TABLE "orders" ADD COLUMN "id" integer COLLATE "C" GENERATED BY DEFAULT AS IDENTITY NOT NULL;',
            'COMMENT ON COLUMN "orders"."id" IS \'pk\';',
        ]);
    });

    it('keeps a literal default verbatim on a new column', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo(),
            plan({ columns: [column({ name: 'code', type: 'text', notNull: true, defaultValue: "'x'" })] })
        );

        expect(statements).toEqual(['ALTER TABLE "orders" ADD COLUMN "code" text DEFAULT \'x\' NOT NULL;']);
    });

    it('adds a nullable column with neither a default nor a comment', () => {
        const statements = buildPostgresModifyTableStatements(deps, 'orders', tableInfo(), plan({ columns: [column({ name: 'note', type: 'text' })] }));

        expect(statements).toEqual(['ALTER TABLE "orders" ADD COLUMN "note" text;']);
    });

    it('adds a primary key to a table that has none', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo(),
            plan({ columns: [column({ name: 'id', type: 'integer', isPrimaryKey: true, primaryKeyOrdinal: 1 })] })
        );

        expect(statements).toEqual(['ALTER TABLE "orders" ADD COLUMN "id" integer;', 'ALTER TABLE "orders" ADD PRIMARY KEY ("id");']);
    });

    it('renames, retypes, defaults and comments an existing column in that order', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({ columns: [columnInfo({ name: 'name', type: 'text' })] }),
            plan({ columns: [column({ name: 'full_name', originalName: 'name', type: 'varchar(255)', notNull: true, defaultValue: "'unknown'", comment: 'display name' })] })
        );

        expect(statements).toEqual([
            'ALTER TABLE "orders" RENAME COLUMN "name" TO "full_name";',
            'ALTER TABLE "orders" ALTER COLUMN "full_name" TYPE varchar(255);',
            'ALTER TABLE "orders" ALTER COLUMN "full_name" SET DEFAULT \'unknown\';',
            'ALTER TABLE "orders" ALTER COLUMN "full_name" SET NOT NULL;',
            'COMMENT ON COLUMN "orders"."full_name" IS \'display name\';',
        ]);
    });

    it('clears a default, a NOT NULL and a comment the plan drops', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({ columns: [columnInfo({ name: 'note', type: 'text', notNull: true, defaultValue: "'x'", comment: 'old' })] }),
            plan({ columns: [keptColumn({ name: 'note', type: 'text' })] })
        );

        expect(statements).toEqual([
            'ALTER TABLE "orders" ALTER COLUMN "note" DROP DEFAULT;',
            'ALTER TABLE "orders" ALTER COLUMN "note" DROP NOT NULL;',
            'COMMENT ON COLUMN "orders"."note" IS NULL;',
        ]);
    });

    it('refuses a collation change instead of emitting a statement it cannot run', () => {
        expect(() =>
            buildPostgresModifyTableStatements(
                deps,
                'orders',
                tableInfo({ columns: [columnInfo({ name: 'name', type: 'text' })] }),
                plan({ columns: [keptColumn({ name: 'name', type: 'text', collation: 'C' })] })
            )
        ).toThrow('PostgreSQL does not support changing collation for existing column name here.');
    });

    it('refuses an identity change on an existing column', () => {
        expect(() =>
            buildPostgresModifyTableStatements(
                deps,
                'orders',
                tableInfo({ columns: [columnInfo({ name: 'id', type: 'integer' })] }),
                plan({ columns: [keptColumn({ name: 'id', type: 'integer', isAutoIncrement: true })] })
            )
        ).toThrow('PostgreSQL identity changes for column id are not supported in Modify Table yet.');
    });

    it('drops the constraints, the index, the primary key and the column that left the plan', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({
                columns: [
                    columnInfo({ name: 'id', type: 'integer', notNull: true, isPrimaryKey: true, primaryKeyOrdinal: 1 }),
                    columnInfo({ name: 'name', type: 'text' }),
                    columnInfo({ name: 'legacy', type: 'text' }),
                ],
                indexes: [
                    indexInfo({ name: 'PRIMARY', columns: ['id'], isUnique: true }),
                    indexInfo({ name: 'uq_name', columns: ['name'], isUnique: true }),
                    indexInfo({ name: 'ix_created', columns: ['created'] }),
                ],
                foreignKeys: [foreignKeyInfo()],
            }),
            plan({
                columns: [keptColumn({ name: 'id', type: 'integer', notNull: true, isPrimaryKey: true, primaryKeyOrdinal: 1 }), keptColumn({ name: 'name', type: 'varchar(255)' })],
                keys: [{ name: 'PRIMARY', isPrimary: true, columns: [{ columnName: 'name' }] }],
            })
        );

        expect(statements).toEqual([
            'ALTER TABLE "orders" DROP CONSTRAINT "fk_owner";',
            'ALTER TABLE "orders" DROP CONSTRAINT "uq_name";',
            'DROP INDEX "ix_created";',
            'ALTER TABLE "orders" DROP CONSTRAINT "orders_pkey";',
            'ALTER TABLE "orders" DROP COLUMN "legacy";',
            'ALTER TABLE "orders" ALTER COLUMN "name" TYPE varchar(255);',
            'ALTER TABLE "orders" ADD PRIMARY KEY ("name");',
        ]);
    });

    it('adds a unique constraint, a typed index and a foreign key with its referential actions', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({
                columns: [
                    columnInfo({ name: 'email', type: 'text' }),
                    columnInfo({ name: 'created', type: 'timestamp' }),
                    columnInfo({ name: 'owner_id', type: 'integer' }),
                    columnInfo({ name: 'tenant', type: 'integer' }),
                ],
            }),
            plan({
                columns: [
                    keptColumn({ name: 'email', type: 'text' }),
                    keptColumn({ name: 'created', type: 'timestamp' }),
                    keptColumn({ name: 'owner_id', type: 'integer' }),
                    keptColumn({ name: 'tenant', type: 'integer' }),
                ],
                keys: [{ name: 'uq_email', isPrimary: false, columns: [{ columnName: 'email' }] }],
                indexes: [{ name: 'ix_created', comment: null, isUnique: true, type: 'BTREE', columns: [{ columnName: 'created', order: 'DESC' }] }],
                foreignKeys: [
                    {
                        name: 'fk_owner',
                        targetTable: 'users',
                        columns: [
                            { columnName: 'owner_id', targetName: 'id' },
                            { columnName: 'tenant', targetName: 'tenant' },
                        ],
                        onDelete: 'CASCADE',
                        onUpdate: 'SET_NULL',
                        match: 'full',
                    },
                ],
            })
        );

        expect(statements).toEqual([
            'ALTER TABLE "orders" ADD CONSTRAINT "uq_email" UNIQUE ("email");',
            'CREATE UNIQUE INDEX "ix_created" USING BTREE ON "orders" ("created" DESC);',
            'ALTER TABLE "orders" ADD CONSTRAINT "fk_owner" FOREIGN KEY ("owner_id", "tenant") REFERENCES "users" ("id", "tenant") MATCH FULL ON DELETE CASCADE ON UPDATE SET NULL;',
        ]);
    });

    it('creates a plain index without USING when the plan has no type', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({ columns: [columnInfo({ name: 'owner_id', type: 'integer' })] }),
            plan({
                columns: [keptColumn({ name: 'owner_id', type: 'integer' })],
                indexes: [{ name: 'ix_owner', comment: null, isUnique: false, type: null, columns: [{ columnName: 'owner_id', order: null }] }],
            })
        );

        expect(statements).toEqual(['CREATE INDEX "ix_owner" ON "orders" ("owner_id");']);
    });

    it('omits MATCH and the referential actions a foreign key does not declare', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({ columns: [columnInfo({ name: 'owner_id', type: 'integer' })] }),
            plan({
                columns: [keptColumn({ name: 'owner_id', type: 'integer' })],
                foreignKeys: [{ name: 'fk_owner', targetTable: 'users', columns: [{ columnName: 'owner_id', targetName: 'id' }], onDelete: null, onUpdate: null, match: null }],
            })
        );

        expect(statements).toEqual(['ALTER TABLE "orders" ADD CONSTRAINT "fk_owner" FOREIGN KEY ("owner_id") REFERENCES "users" ("id");']);
    });

    it('clears a table comment the plan removes', () => {
        const statements = buildPostgresModifyTableStatements(deps, 'orders', tableInfo({ comment: 'old' }), plan());

        expect(statements).toEqual(['COMMENT ON TABLE "orders" IS NULL;']);
    });

    it('writes the table comment and the rename the plan asks for', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({ comment: 'old' }),
            plan({ table: { name: 'orders_v2', comment: "owner's table", engine: null, collation: null, options: null } })
        );

        expect(statements).toEqual(["COMMENT ON TABLE \"orders\" IS 'owner''s table';", 'ALTER TABLE "orders" RENAME TO "orders_v2";']);
    });

    it('emits nothing when the plan already matches the table', () => {
        const statements = buildPostgresModifyTableStatements(
            deps,
            'orders',
            tableInfo({
                columns: [
                    columnInfo({ name: 'id', type: 'integer', notNull: true, isPrimaryKey: true, primaryKeyOrdinal: 1 }),
                    columnInfo({ name: 'owner_id', type: 'integer' }),
                    columnInfo({ name: 'email', type: 'text' }),
                    columnInfo({ name: 'created', type: 'timestamp' }),
                ],
                indexes: [
                    indexInfo({ name: 'PRIMARY', columns: ['id'], isUnique: true }),
                    indexInfo({ name: 'uq_email', columns: ['email'], isUnique: true }),
                    indexInfo({ name: 'ix_created', columns: ['created'], orders: ['DESC'] }),
                ],
                foreignKeys: [foreignKeyInfo()],
            }),
            plan({
                columns: [
                    keptColumn({ name: 'id', type: 'integer', notNull: true, isPrimaryKey: true, primaryKeyOrdinal: 1 }),
                    keptColumn({ name: 'owner_id', type: 'integer' }),
                    keptColumn({ name: 'email', type: 'text' }),
                    keptColumn({ name: 'created', type: 'timestamp' }),
                ],
                keys: [
                    { name: 'PRIMARY', isPrimary: true, columns: [{ columnName: 'id' }] },
                    { name: 'uq_email', isPrimary: false, columns: [{ columnName: 'email' }] },
                ],
                indexes: [{ name: 'ix_created', comment: null, isUnique: false, type: null, columns: [{ columnName: 'created', order: 'DESC' }] }],
                foreignKeys: [
                    {
                        name: 'fk_owner',
                        targetTable: 'users',
                        columns: [{ columnName: 'owner_id', targetName: 'id' }],
                        onDelete: 'NO ACTION',
                        onUpdate: 'NO ACTION',
                        match: 'NONE',
                    },
                ],
            })
        );

        expect(statements).toEqual([]);
    });
});
