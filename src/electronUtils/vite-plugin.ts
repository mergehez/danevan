import type { ChildProcess } from 'child_process';
import { exec, execSync } from 'child_process';
import fs from 'fs';
import { join, resolve } from 'path';
import type { PluginOption } from 'vite';
import { appConfig } from './helpers.ts';

type Options = {
    app: string;
    main: string;
    preload: string;
    devServer: string;
    apiMethods: string;
    /** Files besides `main` that declare native handlers; `main` is always included. */
    nativeMethods?: string[];

    externalize?: string[];
};

/**
 * Handler names the renderer's task table is built from: the backend handlers in
 * `export const app = {` plus the native handlers in the main entry and the files it lists.
 * The IIFE getters (`name: (() => { ... })()`) are not request handlers and are skipped.
 */
export function extractApiMethods(appSource: string, ...nativeSources: string[]): string[] {
    const appLines = appSource.split('export const app = {').pop()!.split('\n');
    const backendMethods = [...appSource.matchAll(/^    ([a-zA-Z]+):\s+(async\s+)?\(/gm)]
        .filter((m) => {
            const lineIndex = appSource.substring(0, m.index).split('\n').length - 1;
            const line = appLines[lineIndex];
            return !/:\s*\(\(\)/.test(line);
        })
        .map((m) => m[1]);

    const nativeMethods = nativeSources.flatMap((source) => [...source.matchAll(/^\s+([a-zA-Z]+):\s+async\s+\(/gm)].map((m) => m[1]));

    return [...new Set([...backendMethods, ...nativeMethods])].sort();
}

function generateApiMethods(paths: Options) {
    const appContent = fs.readFileSync(paths.app, 'utf-8');
    const nativeSources = [paths.main, ...(paths.nativeMethods ?? [])].map((file) => fs.readFileSync(file, 'utf-8'));
    const names = extractApiMethods(appContent, ...nativeSources)
        .map((name) => `'${name}'`)
        .join(',\n    ');

    let content = '// This file is auto-generated by src/electronUtils/vite-plugin.ts';
    content += `\nexport const apiMethods = [\n    ${names},\n] as const;\n`;

    // Rewriting an identical file still invalidates the renderer's module graph (the app remounts
    // and flashes) and re-triggers file watchers such as the test runner that loaded this config.
    if (fs.existsSync(paths.apiMethods) && fs.readFileSync(paths.apiMethods, 'utf-8') === content) {
        return;
    }

    fs.writeFileSync(paths.apiMethods, content);
}

const buildElectronAssets = (paths: Options) => {
    const projectRoot = resolve(import.meta.dirname ?? process.cwd(), '../..');
    const outDir = resolve(projectRoot, 'dist-electron');

    // Clean stale electron builds — vite only empties its own outDir (dist/),
    // not dist-electron/.  rolldown's caching can also skip recompilation.
    if (fs.existsSync(outDir)) {
        fs.rmSync(outDir, { recursive: true, force: true });
    }
    fs.mkdirSync(outDir, { recursive: true });

    const cfgs = [
        { src: paths.main, out: join(outDir, 'main.cjs'), external: ['electron', 'better-sqlite3', ...(paths.externalize || [])] },
        { src: paths.preload, out: join(outDir, 'preload.cjs'), external: ['electron'] },
        { src: paths.devServer, out: join(outDir, 'backend.cjs'), external: ['better-sqlite3'] },
    ];
    console.log('⚡ [Rolldown] Compiling Electron main, preload, and backend targets...');
    for (const cfg of cfgs) {
        const externalFlags = cfg.external.map((id) => `-e ${id}`).join(' ');
        execSync(`bunx rolldown ${cfg.src} --file=${cfg.out} ${externalFlags} --platform=node --format=cjs --no-code-splitting`, { stdio: 'inherit' });
    }
};

let electronProcess: ChildProcess | null = null;

function killStaleServers(...ports: number[]) {
    for (const port of ports) {
        try {
            // Listening processes only, and never ourselves: a restarted dev server may still own its port.
            const pids = execSync(`lsof -ti:${port} -sTCP:LISTEN || true`)
                .toString()
                .split('\n')
                .map((value) => Number.parseInt(value, 10))
                .filter((pid) => Number.isInteger(pid) && pid !== process.pid);

            if (pids.length === 0) continue;

            execSync(`kill -9 ${pids.join(' ')}`, { stdio: 'ignore' });
        } catch {
            // port already free, nothing to do
        }
    }
}

// The dev scripts are `vite` and `vite --mode desktop`; vitest and builds never own these ports
// even though they load this config and create a server.
function ownsDevPorts(mode: string) {
    return mode === 'development' || mode === 'desktop';
}

function watchDevServer(server: any, paths: Options) {
    const isDesktopMode = server.config.mode === 'desktop';

    if (!isDesktopMode) {
        console.log('🌐 Browser Dev Mode active. Mounting devServer via Vite ModuleRunner...');
        server.httpServer?.once('listening', async () => {
            try {
                const backendRunner = (server.environments as any).ssr?.runner;
                if (backendRunner) {
                    await backendRunner.import(paths.devServer);
                    console.log('🚀 Backend devServer successfully instantiated inside Vite.');
                } else {
                    console.warn('⚠️ SSR environment runner not found.');
                }
            } catch (error) {
                console.error('❌ Vite failed to load your background devServer script:', error);
            }
        });
    } else {
        console.log('🖥️  Desktop Dev Mode active. Preparing asset dependencies...');
        buildElectronAssets(paths);

        server.httpServer?.once('listening', () => {
            const addressInfo = server.httpServer?.address();
            if (addressInfo) {
                console.log('📱 Frontend asset stream active. Instantiating Electron window...');

                electronProcess = exec('electron . --dev', {
                    env: { ...process.env, VITE_DEV2: 'true' },
                });

                electronProcess.on('error', (err) => {
                    // Fallback restoration in case of an instant boot failure
                    // fs.writeFileSync(packageJsonPath, rawPackageJson);
                    console.error('Electron run failed:', err);
                });
            }
        });
    }

    process.on('exit', () => {
        electronProcess?.kill();
    });
}

const electronPlugin = (paths: Options): PluginOption => {
    paths.app = resolve(paths.app);
    paths.main = resolve(paths.main);
    paths.preload = resolve(paths.preload);
    paths.devServer = resolve(paths.devServer);
    paths.apiMethods = resolve(paths.apiMethods);
    paths.nativeMethods = paths.nativeMethods?.map((file) => resolve(file));

    let isProductionBuild = false;

    return {
        name: 'export-api-methods',

        config(_config, env) {
            isProductionBuild = env.command === 'build';

            return {
                environments: {
                    ssr: {
                        resolve: {
                            conditions: ['node'],
                        },
                    },
                },
            };
        },
        buildStart() {
            // `bun do mac` runs a production build, so stop whatever still holds the app
            // ports first: the running installed app serves its backend on the API port
            // and a leftover dev server holds the UI port. Otherwise the rebuild (and the
            // later /Applications replacement) races the still-open app.
            if (isProductionBuild) {
                console.log('Stopping the running app and dev servers before building...');
                killStaleServers(appConfig.apiPort, appConfig.vuePort);
            }

            generateApiMethods(paths);
        },
        configureServer(server) {
            // Vitest also creates a dev server, so killing by port from every config load would
            // tear down the dev session that owns these ports.
            if (ownsDevPorts(server.config.mode)) {
                killStaleServers(appConfig.apiPort, appConfig.vuePort);
            }

            server.watcher.add([paths.app, paths.main, ...(paths.nativeMethods ?? [])]);
            server.watcher.on('change', (file) => {
                if (file === paths.app || file === paths.main || paths.nativeMethods?.includes(file)) {
                    generateApiMethods(paths);
                }
            });

            watchDevServer(server, paths);
        },

        closeBundle() {
            buildElectronAssets(paths);
        },
    };
};

export default electronPlugin;
